// 3. 架构哲学: 三层分离
// ---------------------------------------------------------------------------
// 设计目标: 耦合场景下人的出错率最低——从来不是单算法使用场景最优;
//   ICPC 金银牌题是流水线(建图→VBCC→BCT→HLD→SegTree), 敌人是算法之间的
//   胶水(格式转换/下标偏移/有向无向重建/命名不一致), 不是算法本身;
//   统一存储 + 接口对齐 = 流水线每条箭头零成本, 短时记忆占用最低,
//   代码手感即此——KACTL/ACL 选单算法最优是战场理性, 本库选耦合最优
//   是训练场理性, 两条路线无优劣, 服务不同目标函数
// - 代数层 Info/Tag —— 每题重写的数据语义, 是唯一跨引擎共享的资产
// - 引擎层 —— 定版后不动; 接口跨引擎同名对齐(modify/query/build/
//   find_first/find_last), 肌肉记忆统一
// - 应用层 solve —— 版本根数组/离散化/组装逻辑全部外置在调用方
// - 裁决: 不把多引擎合并成一份大模板(正确性前提互斥, if constexpr 迷宫
//   判负); 统一的是代数层与命名纪律, 不是代码本身

// ---------------------------------------------------------------------------
// 3.5 高耦合引擎封装策略 (LCT/SAM/网络流/莫队等)
// ---------------------------------------------------------------------------
// 耦合度分档: 按热循环里引擎与题目逻辑的交织深度选封装策略, 禁一刀切
// 第一档·低耦合(现有 OOP+Info/Tag): 平衡树/线段树/堆/并查集——引擎通用,
//   数据不透明, 当前库已覆盖; 新引擎照家族风格归类
// 第二档·中耦合(策略注入): 引擎可复用但核心操作是题目定义的——
//   莫队(调度引擎+lambda add/remove)、Li Chao 树/斜率 trick(代价函数走
//   模板参数)、CDQ 分治(conquer 走 lambda); 模板参数优先于 std::function
//   (编译期单态化保内联), lambda 优于仿 struct (赛场上少一层跳转)
// 第三档·高耦合(自含式题目模板, 引擎不分离): LCT(splay 旋转与路径聚合
//   在热循环逐结点交错, Info/Tag 风格标注 pushup/apply 但整个 struct 就是
//   要抄的模板)、SAM/后缀树/回文自动机(结点数组直接暴露, API 只有
//   extend + 调用方走转移)、网络流(struct 拥有图+算法, rev(i)=i^1 配对
//   是算法核心不是实现细节)、树分块(同莫队但状态更重)
// 裁决: 不用 CRTP——竞赛中比直接改 pushup 多一层模板嵌套, 抄写时多一个
//   出错点; 零开销抽象在赛场上是零收益复杂度; ICPC 实用标准: 抄写成本 >
//   代码复用优雅度; 自含式模板用注释标记题目定制区(如 // ---- 改这里 ----)

