//     防子串误报)
//   ①-⑥ 坏了整体 fail fast; ⑦ 只是黄牌面板。
// run_checks.ps1 自身: 纯 ASCII(PS5.1 把无 BOM 文件按 ANSI 读, CJK 注释
//   会乱码吞行); param() 必须是第一行, 否则参数绑定失效。
