// 对拍的灵魂: 按算法自己的特性, 想尽一切办法用暴力打它。暴力不是模板
// 的翻版, 是从零独立写的最简正确解。参照系从数学本质里选:
//   SCC→传递闭包 | 桥→逐条删边 | 割点→逐个删点 | 点双→子集枚举 |
//   第k小→排序取位 | 持久化→版本快照回放 | 懒标记→全量逐点展开。
// 语义上精确对齐契约: 裸值口径、偏移追踪、平局裁决、边界域。
// 制式: mt19937(42) 定种子, 至少 300 组小规模, assert 逐项比对。
// 暴力必须独立(禁复用模板代码)。
