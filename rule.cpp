// ---------------------------------------------------------------------------
// 9. 验证标准
// ---------------------------------------------------------------------------
// 对拍暴力哲学: 根据算法的特性想尽一切办法暴力测试它——暴力不是模板的
//   翻版, 而是从零独立构造的最简正确解; 结构上利用算法的数学本质选参照系
//   (SCN→可达闭包/桥→逐边删/割点→逐点删/点双→子集枚举/第k小→排序取位/
//   持久化→版本快照回放/懒标记→全量逐点展开), 语义上精确建模契约(裸值
//   口径/偏移追踪/平局裁决/边界域), 在算法竞赛的语境中做到万无一失
// 对拍: mt19937(42) 定种子, ≥300 组小规模, 与暴力 assert 比对;
//   暴力必须与模板算法独立(可达闭包/删边数分量/Menger+极大团), 禁复用模板代码
//   测试自身坑位(挂了先查测试再怀疑模板): 局部类禁定义 friend operator+
//   (Info/Tag 放全局) | 两个临时容器的迭代器配对 UB | 编号体系不同先规范化
//   再比(bel 组号莫再套 bel) | 断点法在端点坐标多算尾巴(坐标点+间隙 2i/2i+1)
//   | 暴力值口径: 全局偏移引擎(gadd 类)的 insert/set_val/乘法一律存裸值,
