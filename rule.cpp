// 测试坑位表(测试挂了先查测试, 再怀疑模板):
// - 局部类里不能定义 friend operator+(Info/Tag 放全局)
// - 两个临时容器的迭代器配对是 UB
// - 两边编号体系不同先规范化再比(bel 的组号别再套 bel)
// - 断点法在端点坐标会多数尾巴(坐标点+间隙 2i/2i+1)
// - 全局偏移型引擎(gadd 类)的暴力, insert/set_val/乘法一律存裸值, 别混真值
// - 暴力重标号循环先缓存 from/to, 循环里改 lab[v] 会污染匹配条件
// - n=1 时 v=u%n+1 采样自环会死循环
// - 割点判定是 cv>c0, 不是 c0-1
// - 报"同名 struct 重定义", 先查守卫, 再怀疑引擎
// - grep 正则命中不等于代码被调用: 注释和 Usage 示例也会命中
//   (// LL read() 那次, 误报了 11 个调用方)。grep 结论必须抽行核对原文。
// - 覆盖类结论禁凭记忆: 声称"都齐了/没有漏"之前, 必须拿一份完整独立大纲
//   逐节 diff(实测: 46 目录对着左程云清单核过, 但莫比乌斯/回文自动机/FFT
//   三个洞全在清单之外, 靠用户直觉抓出来——参照物应是 OI Wiki 全目录这种
//   完整物, 不是任务自带的清单, 更不是记忆); 镜像条款: 排除类结论("这个
//   射程外/已有覆盖")同样禁凭记忆, 必须对照库内资产核实(catalog/§4 现役
//   /对拍清单)——实测把左偏树写成"可并堆射程外", 而它是核心引擎, 镜像
//   错误紧跟着原条款入宪当天就发生
// - 多测开关(cin >> t)留在单测题上 = 炸弹: t 吃掉真正的 n, 输入耗尽后
//   cin 全失效, 循环变量成垃圾值无限刷输出, cph 面板被淹到 VS Code 整个
//   卡死(P3369 实测)。单测题务必删掉那行; 卡死时任务管理器杀题进程。
// - 对拍挂了, 朴素参考也是嫌疑人(HLD 融合实测四轮探针才洗清引擎冤案):
//   同构操作的手写双版要互查对称性——路径加的朴素 while 跳出后漏给 LCA
//   补加, 而查询版有收尾 s+=ref[a], 差恰好 k, 暴露却在两步之后的另一条
//   路径上。排障路径: 确定性小树探针 → OP 逐步 trace → 逐操作复现 →
