//       例外: 可持久化并查集解禁——按秩合并+无路径压缩是纯最坏复杂度
//       O(log n), 无摊还成分, 版本回放安全; find 只读, merge 走可持久化
//       数组的版本化写, 天然函数式(与 §8 函数式引擎风格吻合)。
//       真正禁的是"带路径压缩的持久化"(实测误伤过一次, 用户纠偏)。
