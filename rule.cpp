// ---------------------------------------------------------------------------
// 5. 内存池纪律 (血泪条款)
// ---------------------------------------------------------------------------
// - vector 池: 构造期 reserve(max_nodes+1) + push_back 哨兵 0 号
// - 报警器: 独立成员 int budget/cap 存预算, fork/new_node 里 assert 判它;
//   判 tr.capacity() 无效——扩容会自己推高容量, assert 变恒真死代码
// - 默认预算分口径: 累计插入(删除不回收)统一 4000010(≈4e6, 32B/结点
//   ≈122MB, 兼容 256MB 赛机, 覆盖 n=2e5 静态第k小≈3.8e6); 峰值存活(带
//   id 回收, 如 FHQ_Seq/SGTree)降为 1000010; 类头必须写明口径; 超范围
//   必须显式传参并核算字节。报警器无差别生效: 函数式引擎同样禁静默扩容(PersSegTree 的
//   fork 已接 assert——本地 RE 好过赛场静默 realloc 后 MLE)
// - 铁律: 绝不静默扩容。预算 = (build?2n:0) + m*(ceil(log2 n)+2),
//   范围修改 ×2; Graph::edges 预留 m*(Dir?1:2)+10; 圆方树 2n 点 4m 半边
// - 引用安全 = "永不扩容" 不变式: 全引用回写引擎(DySegTree, Graph 遍历)
//   的 int& 依赖容量恒定; 引用风格者新写代码同此契约
// - 遍历邻接表 / 持有 vector 元素引用期间, 禁止任何 push_back
// - clear(): 计数器归零 + 恢复哨兵, 容量保留; 分配路径必须全字段覆写
//   (push_back(Node{})), 否则跨 clear 复用携带脏字段
// - 成型查询表(LCA 的 rmq/fa)构造期可全量 assign(只此一次); 增长池必须
//   reserve-only。Linux 评测机大 reserve 只占虚拟地址, 本地 Windows 调试
//   可能直接 bad_alloc——用户报莫名内存错误时先想到这条

// ---------------------------------------------------------------------------
// 6. 复位语义: 三分类 × 三流派
// ---------------------------------------------------------------------------
// init(n): 算法器复位。= 委托成员容器 clear + 最小复位集 + n 重配 + 计数器
//          归零。多测场景标配: 全局静态实例 + 每测 init
// clear(): 纯容器复位。O(used) 擦触达部分, 容量保留, n 不变
// set_n(n): 只改值域不碰池 (统一命名 set_n, set_range 是漂移写法, 见到改掉)
// 状态三分类口诀: 清"先读后写"与"只写不清"的字段, 豁免"先写后读"的字段
//   (dfn/rt/cut/deg 必清; low/rmq/fa/rnk 可豁免)
// 复位三流派: 纯容器(只 clear) | 算法器(init 委托) | 重建设(build 自带 clear)
// 职责归属: 谁知道哪些状态脏了, 复位权就在谁那一层

